def build_brief_pdf(brief: dict, is_reviewed: bool = True) -> bytes:
    """Render an AI Case Brief as a professional law-firm memo PDF. Applies watermark if unreviewed."""
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=LETTER, leftMargin=0.85*inch, rightMargin=0.85*inch, topMargin=0.9*inch, bottomMargin=0.9*inch)
    styles = get_styles()
    story  = []

    case_num = brief.get("case_number", "")
    matter   = brief.get("matter", "")
    gen_date = brief.get("generated_at", datetime.now().strftime("%B %d, %Y"))
    risk_sc  = brief.get("risk_score", "N/A")

    conf_style = ParagraphStyle("conf", fontSize=8, fontName="Helvetica-Bold", textColor=colors.HexColor("#c0392b"), alignment=TA_CENTER, spaceAfter=6)
    story.append(Paragraph("PRIVILEGED AND CONFIDENTIAL — ATTORNEY WORK PRODUCT", conf_style))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#c0392b")))
    story.append(Spacer(1, 10))
    story.append(Paragraph("AI Case Brief", styles["title"]))
    story.append(Spacer(1, 8))
    story.append(Paragraph(f"{case_num}  ·  {matter}", styles["subtitle"]))
    story.append(Spacer(1, 6))
    story.append(HRFlowable(width="100%", thickness=2, color=GOLD, spaceAfter=10))

    meta_style = ParagraphStyle("meta", fontSize=8.5, fontName="Helvetica", textColor=GRAY, spaceAfter=12)
    risk_color_hex = ("#c0392b" if isinstance(risk_sc, (int,float)) and risk_sc >= 7 else "#e67e22" if isinstance(risk_sc, (int,float)) and risk_sc >= 4 else "#27ae60")
    risk_label = (f'<font color="{risk_color_hex}"><b>Risk Score: {risk_sc}/10</b></font>' if risk_sc != "N/A" else "Risk Score: N/A")
    story.append(Paragraph(f"Generated: {gen_date} &nbsp;&nbsp;|&nbsp;&nbsp; Prepared by: ParaIQ AI &nbsp;&nbsp;|&nbsp;&nbsp; {risk_label}", meta_style))
    story.append(HRFlowable(width="100%", thickness=0.5, color=LGRAY))
    story.append(Spacer(1, 12))

    sections = brief.get("sections", {})
    section_style = ParagraphStyle("bsec", fontSize=9.5, fontName="Helvetica-Bold", textColor=colors.HexColor("#7c3aed"), spaceBefore=14, spaceAfter=5, textTransform="uppercase", letterSpacing=1)
    body_style = ParagraphStyle("bbody", fontSize=10.5, fontName="Helvetica", textColor=colors.HexColor("#1e293b"), leading=16, spaceAfter=4)

    for key, sec in sections.items():
        title   = sec.get("title", key)
        content = sec.get("content", "")
        if not content: continue
        block = [Paragraph(title, section_style), HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#e2e8f0")), Spacer(1, 4)]
        for line in content.split("\n"):
            line = line.strip()
            if line: block.append(Paragraph(line, body_style))
        story.append(KeepTogether(block))

    story.append(Spacer(1, 20))
    story.append(HRFlowable(width="100%", thickness=0.5, color=GRAY))
    story.append(Spacer(1, 4))
    story.append(make_footer_note(styles))

    # APPLY WATERMARK IF NOT REVIEWED
    if not is_reviewed:
        doc.build(story, onFirstPage=_draw_watermark, onLaterPages=_draw_watermark)
    else:
        doc.build(story)
        
    return buf.getvalue()

