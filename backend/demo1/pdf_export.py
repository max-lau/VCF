@router.get("/brief/{case_id}")
def export_brief_pdf(case_id: int, request: Request):
    """Export the most recent AI Case Brief for a case as a PDF. Applies watermark if not reviewed."""
    firm_id = getattr(request.state, "firm_id", "default")
    
    # MALPRACTICE SHIELD: Check review status
    is_reviewed = is_document_reviewed(doc_id=case_id, firm_id=firm_id)
    
    with get_conn(firm_id) as conn:
        row = conn.execute("SELECT brief_json FROM case_briefs WHERE case_id=%s ORDER BY generated_at DESC LIMIT 1", (case_id,)).fetchone()
    if not row:
        raise HTTPException(404, "No brief found -- generate one first from the case detail page")
    brief = json.loads(row["brief_json"])
    
    pdf = build_brief_pdf(brief, is_reviewed=is_reviewed)
    fname = f"ParaIQ_Brief_{brief.get('case_number','case').replace('/','-').replace(' ','_')}.pdf"
    return Response(content=pdf, media_type="application/pdf", headers={"Content-Disposition": f'attachment; filename="{fname}"'})

# ── MALPRACTICE SHIELD: ATTORNEY REVIEW ENDPOINT ──────────────────────────────
@router.post("/brief/{case_id}/confirm-review")
def confirm_review(case_id: int, request: Request):
    """Attorney confirms they have read the AI document. Logs to audit trail."""
    firm_id = getattr(request.state, "firm_id", "default")
    attorney_id = getattr(request.state, "user_id", "unknown_attorney")
    
    try:
        log_attorney_review(doc_id=case_id, attorney_id=attorney_id, firm_id=firm_id)
        return {"status": "success", "message": "Review logged. Watermark removed."}
    except Exception as e:
        raise HTTPException(500, f"Failed to log review: {str(e)}")
