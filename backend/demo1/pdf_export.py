class AnalysisExportBody(BaseModel):
    text:      str
    sentiment: Optional[str] = None
    score:     Optional[float] = None
    entities:  Optional[list] = []
    language:  Optional[str] = "en"
    label:     Optional[str] = "Analysis"

class RiskExportBody(BaseModel):
    text:    str
    context: Optional[str] = None
    label:   Optional[str] = "Document"

@router.post("/analysis")
def export_analysis_pdf(body: AnalysisExportBody):
    data = body.dict()
    data["text_length"] = len(body.text)
    pdf_bytes = build_analysis_pdf(data)
    return StreamingResponse(io.BytesIO(pdf_bytes), media_type="application/pdf", headers={"Content-Disposition": f'attachment; filename="analysis_{datetime.now().strftime("%Y%m%d_%H%M%S")}.pdf"'})

@router.post("/risk")
def export_risk_pdf(body: RiskExportBody):
    from backend.demo1.risk_scorer import score_text
    risk = score_text(body.text, context=body.context)
    pdf_bytes = build_risk_pdf(risk, label=body.label)
    return StreamingResponse(io.BytesIO(pdf_bytes), media_type="application/pdf", headers={"Content-Disposition": f'attachment; filename="risk_report_{datetime.now().strftime("%Y%m%d_%H%M%S")}.pdf"'})

@router.get("/case/{case_id}")
def export_case_pdf(case_id: int, request: Request):
    firm_id = getattr(request.state, "firm_id", "default")
    with get_conn(firm_id) as conn:
        case = conn.execute("SELECT * FROM cases WHERE id=%s AND deleted=0", (case_id,)).fetchone()
        if not case: raise HTTPException(404, f"Case {case_id} not found")
        docs = conn.execute("SELECT * FROM case_documents WHERE case_id=%s ORDER BY upload_date DESC", (case_id,)).fetchall()
    pdf_bytes = build_case_pdf(dict(case), [dict(d) for d in docs])
    case_num  = dict(case).get("case_number", str(case_id)).replace("/", "-")
    return StreamingResponse(io.BytesIO(pdf_bytes), media_type="application/pdf", headers={"Content-Disposition": f'attachment; filename="case_{case_num}.pdf"'})

