# ── Style helpers ──────────────────────────────────────────────────────────────
DARK   = colors.HexColor("#1a1a2e")
GOLD   = colors.HexColor("#c9a84c")
RED    = colors.HexColor("#c0392b")
GREEN  = colors.HexColor("#27ae60")
GRAY   = colors.HexColor("#7f8c8d")
LGRAY  = colors.HexColor("#ecf0f1")

def get_styles():
    base = getSampleStyleSheet()
    styles = {
        "title": ParagraphStyle("title", fontSize=22, textColor=DARK, fontName="Helvetica-Bold", spaceAfter=4, alignment=TA_LEFT),
        "subtitle": ParagraphStyle("subtitle", fontSize=11, textColor=GRAY, fontName="Helvetica", spaceAfter=12, alignment=TA_LEFT),
        "section": ParagraphStyle("section", fontSize=13, textColor=DARK, fontName="Helvetica-Bold", spaceBefore=14, spaceAfter=6),
        "body": ParagraphStyle("body", fontSize=9, textColor=colors.black, fontName="Helvetica", spaceAfter=4, leading=14),
        "small": ParagraphStyle("small", fontSize=8, textColor=GRAY, fontName="Helvetica", spaceAfter=2),
        "label": ParagraphStyle("label", fontSize=8, textColor=GRAY, fontName="Helvetica-Bold", spaceAfter=1),
        "value": ParagraphStyle("value", fontSize=10, textColor=DARK, fontName="Helvetica-Bold", spaceAfter=4),
    }
    return styles

def risk_color(level: str):
    return {
        "critical": colors.HexColor("#c0392b"),
        "high":     colors.HexColor("#e67e22"),
        "medium":   colors.HexColor("#f39c12"),
        "low":      colors.HexColor("#27ae60"),
        "minimal":  colors.HexColor("#2980b9"),
    }.get(level, GRAY)

def make_header(story, styles, title, subtitle=None):
    story.append(Paragraph(title, styles["title"]))
    if subtitle:
        story.append(Paragraph(subtitle, styles["subtitle"]))
    story.append(HRFlowable(width="100%", thickness=2, color=GOLD, spaceAfter=12))

def make_kv_table(data: list, col_widths=None):
    col_widths = col_widths or [2.2*inch, 4.3*inch]
    table = Table(data, colWidths=col_widths)
    table.setStyle(TableStyle([
        ("BACKGROUND",  (0,0), (0,-1), LGRAY),
        ("FONTNAME",    (0,0), (0,-1), "Helvetica-Bold"),
        ("FONTNAME",    (1,0), (1,-1), "Helvetica"),
        ("FONTSIZE",    (0,0), (-1,-1), 9),
        ("TEXTCOLOR",   (0,0), (0,-1), DARK),
        ("ROWBACKGROUNDS", (0,0), (-1,-1), [colors.white, colors.HexColor("#f8f9fa")]),
        ("GRID",        (0,0), (-1,-1), 0.5, colors.HexColor("#dee2e6")),
        ("VALIGN",      (0,0), (-1,-1), "TOP"),
        ("TOPPADDING",  (0,0), (-1,-1), 5),
        ("BOTTOMPADDING",(0,0),(-1,-1), 5),
        ("LEFTPADDING", (0,0), (-1,-1), 8),
    ]))
    return table

def make_footer_note(styles):
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    return Paragraph(f"Generated by NLP Text Analyzer API · {now}", styles["small"])

# ── MALPRACTICE SHIELD: UNREVIEWED WATERMARK ───────────────────────────────────
def _draw_watermark(canvas, doc):
    """Draws a massive red diagonal watermark on every page."""
    canvas.saveState()
    canvas.setFont('Helvetica-Bold', 60)
    canvas.setFillColor(colors.red, alpha=0.3)
    # Diagonal text
    canvas.translate(LETTER[0]/2.0, LETTER[1]/2.0)
    canvas.rotate(45)
    canvas.drawCentredString(0, 0, "UNREVIEWED AI DRAFT")
    canvas.drawCentredString(0, -60, "MALPRACTICE RISK - NOT FOR PRODUCTION")
    canvas.restoreState()

