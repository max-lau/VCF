    doc    = SimpleDocTemplate(buf, pagesize=LETTER, leftMargin=0.85*inch, rightMargin=0.85*inch, topMargin=0.9*inch, bottomMargin=0.9*inch)
    styles = get_styles()
    story  = []
    make_header(story, styles, "Case Summary Report", f"{case.get('client_name','Unknown')} · {case.get('case_number','')}")
    story.append(Paragraph("Case Information", styles["section"]))
    data = [
        ["Case Number",  case.get("case_number", "N/A")], ["Client",       case.get("client_name", "N/A")],
        ["Court",        case.get("court", "N/A")], ["Judge",        case.get("judge", "N/A")],
        ["Status",       case.get("status", "N/A").upper()], ["Risk Level",   case.get("risk_level", "unknown").upper()],
        ["Filing Date",  case.get("filing_date", "N/A")],
    ]
    story.append(make_kv_table(data))
    story.append(Spacer(1, 10))
    desc = case.get("description", "")
    if desc:
        story.append(Paragraph("Description", styles["section"]))
        story.append(Paragraph(desc, styles["body"]))
        story.append(Spacer(1, 8))
    if documents:
        story.append(Paragraph(f"Documents ({len(documents)})", styles["section"]))
        rows = [["Document", "Source", "Sentiment", "Risk Score", "Added"]]
        for d in documents:
            rows.append([d.get("document_name", "")[:40], d.get("source", ""), d.get("sentiment", "N/A") or "N/A", str(d.get("risk_score", "N/A") or "N/A"), (d.get("created_at", "") or "")[:10]])
